public class GabungString_M44 {
    public static void main(String[] args) {
        // 1. Deklarasi dan instansiasi dua object String terpisah
        String kataPertama = "Pemrograman";
        String kataKedua = "Java";

        // 2. Menggabungkan keduanya menggunakan operator '+' dan menetapkannya ke String ketiga
        String hasilGabungan = kataPertama + " " + kataKedua;

        // Menampilkan hasil
        System.out.println(hasilGabungan); // Output: Pemrograman Java
    }
}